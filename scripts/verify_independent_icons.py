from __future__ import annotations

"""Verify ClassicBar standalone icon placeholders.

These placeholder icons are generated by this repository's own scripts and are
not extracted from Minecraft or third-party mods.

Compat fallback icons (blood/thirst/stamina/feathers) are reserved placeholder
files only. Their presence keeps stable replacement paths available while the
corresponding compat overlays remain quarantined; it does not mean compat
support has been restored.
"""

